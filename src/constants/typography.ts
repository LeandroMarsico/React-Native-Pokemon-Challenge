/** Named type sizes, so components pass a size like `LG` instead of a raw pixel value. */
export enum FontSize {
  SM = 'sm',
  MD = 'md',
  LG = 'lg',
  XL = 'xl',
  XXL = 'xxl',
}

/** Named font weights, matching the numeric weights already used across the app. */
export enum FontWeight {
  REGULAR = 'regular',
  SEMIBOLD = 'semibold',
  BOLD = 'bold',
}
